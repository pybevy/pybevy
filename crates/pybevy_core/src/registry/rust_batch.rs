//! Batch component type for Rust-side components (e.g., PointLight, SpotLight).
//!
//! `PyRustComponentBatch` stores a component type pointer plus normalized field
//! columns. The actual insertion is delegated to a macro-generated typed
//! function via `ComponentBatchMeta`.

use std::{collections::HashMap, sync::Arc};

use bevy::ecs::{entity::Entity, world::World};
use pybevy_storage::batch_columns::{
    BatchScalar, IntegerColumn, check_batch_integer, check_batch_integer_f32,
};
use pyo3::{
    PyTraverseError, PyVisit,
    exceptions::{PyOverflowError, PyTypeError, PyValueError},
    prelude::*,
    types::{PyBool, PyDict, PyList, PyTuple},
};

use super::{
    batch_bridge::{BatchComponent, PreparedBatchComponent},
    global_registry,
};

/// Batch component for Rust-side components (auto-generated by macro).
///
/// Created via `PointLight.batch(intensity=intensities, range=ranges)`.
/// External NumPy inputs retain their normalized arrays. Portable Python
/// sequences and bounded arrays are snapshotted into owned f32 columns.
#[pyclass(name = "RustComponentBatch")]
pub struct PyRustComponentBatch {
    /// Pointer to the component's Python type (for registry lookup)
    pub component_type_ptr: usize,
    /// Field name → numpy array (stored as Py<PyAny>)
    pub field_arrays: HashMap<String, Py<PyAny>>,
    /// Field name → owned contiguous f32 values for dependency-free inputs.
    pub field_values: HashMap<String, Vec<f32>>,
    /// Number of entities to spawn
    pub count: usize,
    /// Component name for error messages
    pub component_name: String,
}

#[pymethods]
impl PyRustComponentBatch {
    fn __traverse__(&self, visit: PyVisit<'_>) -> Result<(), PyTraverseError> {
        for array in self.field_arrays.values() {
            visit.call(array)?;
        }
        Ok(())
    }

    /// Get the number of entities in this batch
    fn __len__(&self) -> usize {
        self.count
    }

    /// The Batchable protocol's method. Same number as `len()`.
    fn count(&self) -> usize {
        self.count
    }
}

impl PyRustComponentBatch {
    /// Get a field array by name, bound to the current Python context.
    pub fn get_field_array<'py>(&self, py: Python<'py>, name: &str) -> Option<Bound<'py, PyAny>> {
        self.field_arrays.get(name).map(|a| a.bind(py).clone())
    }

    /// Get an owned portable field column by name.
    pub fn get_field_values(&self, name: &str) -> Option<&[f32]> {
        self.field_values.get(name).map(Vec::as_slice)
    }
}

/// Snapshot a plain sequence or bounded array as an owned contiguous f32 column.
///
/// External arrays return `None` so the existing NumPy adapter remains their
/// normalization path. The bounded-array converter holds all validity and
/// storage guards for the complete synchronous copy.
pub fn portable_f32_batch_column(
    value: &Bound<'_, PyAny>,
) -> PyResult<Option<(Vec<usize>, Vec<f32>)>> {
    let is_sequence = value.is_instance_of::<PyList>() || value.is_instance_of::<PyTuple>();
    let array_module = value.py().import("pybevy.array")?;
    let is_bounded_array = value.is_instance(&array_module.getattr("Array")?)?;
    if !is_sequence && !is_bounded_array {
        return Ok(None);
    }

    let kwargs = PyDict::new(value.py());
    kwargs.set_item("dtype", array_module.getattr("float32")?)?;
    let normalized = array_module
        .getattr("asarray")?
        .call((value,), Some(&kwargs))?;
    let shape = normalized.getattr("shape")?.extract()?;
    let values = normalized
        .call_method0("ravel")?
        .call_method0("tolist")?
        .extract()?;
    Ok(Some((shape, values)))
}

/// Reject `batch` inputs an integer column cannot hold before any cast runs.
///
/// Out-of-range values raise `ValueError` and non-integral values `TypeError`.
/// The message names `name`, the offending input as given, and its row. NumPy
/// arrays are checked with vectorized reductions, lists, tuples, and bounded
/// arrays element by element; other inputs are left to the caller's
/// normalization.
pub fn check_integer_batch_column(
    value: &Bound<'_, PyAny>,
    name: &str,
    column: IntegerColumn,
) -> PyResult<()> {
    check_column(value, name, column, false)
}

/// [`check_integer_batch_column`] for a native `batch` column carried as
/// `f32`, which also rejects, with `ValueError`, values the field would not
/// store exactly.
pub fn check_f32_integer_batch_column(
    value: &Bound<'_, PyAny>,
    name: &str,
    column: IntegerColumn,
) -> PyResult<()> {
    check_column(value, name, column, true)
}

fn check_column(
    value: &Bound<'_, PyAny>,
    name: &str,
    column: IntegerColumn,
    carried_f32: bool,
) -> PyResult<()> {
    if value.is_instance_of::<PyList>() || value.is_instance_of::<PyTuple>() {
        for (row, item) in value.try_iter()?.enumerate() {
            check_integer_items(&item?, name, column, carried_f32, row)?;
        }
        return Ok(());
    }
    let py = value.py();
    if value.is_instance(&py.import("pybevy.array")?.getattr("Array")?)? {
        let items = value.call_method0("ravel")?.call_method0("tolist")?;
        let stride = row_stride(value, items.len()?)?;
        for (index, item) in items.try_iter()?.enumerate() {
            check_integer_scalar(&item?, name, column, carried_f32, index / stride)?;
        }
        return Ok(());
    }
    // Unsupported inputs keep the caller's own column-type error.
    let Ok(np) = py.import("numpy") else {
        return Ok(());
    };
    if !value.hasattr("__array__")? {
        return Ok(());
    }
    let array = np.call_method1("ravel", (value,))?;
    let kind: String = array.getattr("dtype")?.getattr("kind")?.extract()?;
    let len = array.len()?;
    if kind == "b" || len == 0 {
        return Ok(());
    }
    let stride = row_stride(value, len)?;
    if !matches!(kind.as_str(), "i" | "u" | "f") {
        let items = array.call_method0("tolist")?;
        for (index, item) in items.try_iter()?.enumerate() {
            check_integer_scalar(&item?, name, column, carried_f32, index / stride)?;
        }
        return Ok(());
    }
    if kind == "f" {
        let integral = np.call_method1(
            "logical_and",
            (
                np.call_method1("isfinite", (&array,))?,
                np.call_method1("equal", (np.call_method1("trunc", (&array,))?, &array))?,
            ),
        )?;
        if !integral.call_method0("all")?.is_truthy()? {
            let first: usize = np.call_method1("argmin", (&integral,))?.extract()?;
            return check_integer_scalar(
                &array.get_item(first)?,
                name,
                column,
                carried_f32,
                first / stride,
            );
        }
    }
    for reduction in ["argmin", "argmax"] {
        let index: usize = array.call_method0(reduction)?.extract()?;
        check_integer_scalar(
            &array.get_item(index)?,
            name,
            column,
            carried_f32,
            index / stride,
        )?;
    }
    if !carried_f32 {
        return Ok(());
    }
    // Mirror the f32 carry and the saturating cast into the field.
    let (low, high) = column.bounds();
    let carried = array
        .call_method1("astype", ("float32",))?
        .call_method1("astype", ("float64",))?;
    let stored = np.call_method1("clip", (carried, low as f64, high as f64))?;
    let exact = np.call_method1(
        "equal",
        (stored, array.call_method1("astype", ("float64",))?),
    )?;
    if !exact.call_method0("all")?.is_truthy()? {
        let first: usize = np.call_method1("argmin", (&exact,))?.extract()?;
        return check_integer_scalar(
            &array.get_item(first)?,
            name,
            column,
            carried_f32,
            first / stride,
        );
    }
    Ok(())
}

/// Flat elements per row of `value`, whose raveled length is `len`.
fn row_stride(value: &Bound<'_, PyAny>, len: usize) -> PyResult<usize> {
    let rows = value.len()?;
    Ok(len.checked_div(rows).unwrap_or(1).max(1))
}

fn check_integer_items(
    item: &Bound<'_, PyAny>,
    name: &str,
    column: IntegerColumn,
    carried_f32: bool,
    row: usize,
) -> PyResult<()> {
    if item.is_instance_of::<PyList>() || item.is_instance_of::<PyTuple>() {
        for inner in item.try_iter()? {
            check_integer_items(&inner?, name, column, carried_f32, row)?;
        }
        Ok(())
    } else {
        check_integer_scalar(item, name, column, carried_f32, row)
    }
}

fn check_integer_scalar(
    item: &Bound<'_, PyAny>,
    name: &str,
    column: IntegerColumn,
    carried_f32: bool,
    row: usize,
) -> PyResult<()> {
    let scalar = if item.is_instance_of::<PyBool>() {
        BatchScalar::Int(i128::from(item.is_truthy()?))
    } else {
        match item.extract::<i128>() {
            Ok(integer) => BatchScalar::Int(integer),
            Err(error) if error.is_instance_of::<PyOverflowError>(item.py()) => {
                BatchScalar::BigInt(item.str()?.to_string())
            }
            Err(_) => match item.extract::<f64>() {
                Ok(float) => BatchScalar::Float(float),
                Err(_) => BatchScalar::Other(item.repr()?.to_string()),
            },
        }
    };
    let checked = if carried_f32 {
        check_batch_integer_f32(name, column, scalar)
    } else {
        check_batch_integer(name, column, scalar)
    };
    checked.map_err(|error| {
        let error = error.at_row(row);
        if error.is_value_error() {
            PyValueError::new_err(error.to_string())
        } else {
            PyTypeError::new_err(error.to_string())
        }
    })
}

/// Bridge for RustComponentBatch that implements BatchComponent.
pub struct RustComponentBatchBridge;

impl BatchComponent for RustComponentBatchBridge {
    fn name(&self) -> &'static str {
        "RustComponentBatch"
    }

    fn component_type_ptr(&self, _py: Python, batch: &Bound<PyAny>) -> PyResult<usize> {
        Ok(batch
            .extract::<PyRef<PyRustComponentBatch>>()?
            .component_type_ptr)
    }

    fn count(&self, _py: Python, batch: &Bound<PyAny>) -> PyResult<usize> {
        let batch = batch.extract::<PyRef<PyRustComponentBatch>>()?;
        Ok(batch.count)
    }

    fn prepare(
        &self,
        py: Python,
        batch: &Bound<PyAny>,
    ) -> PyResult<Box<dyn PreparedBatchComponent>> {
        let batch = batch.extract::<PyRef<PyRustComponentBatch>>()?;
        let meta = global_registry::get_component_batch_meta(batch.component_type_ptr).ok_or_else(
            || {
                PyValueError::new_err(format!(
                    "No batch metadata registered for component '{}' (type ptr: 0x{:x})",
                    batch.component_name, batch.component_type_ptr
                ))
            },
        )?;
        (meta.prepare_fn)(py, &batch)
    }

    fn insert_bulk(
        &self,
        py: Python,
        batch: &Bound<PyAny>,
        entities: &[Entity],
        world: &mut World,
    ) -> PyResult<()> {
        let batch = batch.extract::<PyRef<PyRustComponentBatch>>()?;

        // Look up the ComponentBatchMeta for this component type
        let meta = global_registry::get_component_batch_meta(batch.component_type_ptr).ok_or_else(
            || {
                PyValueError::new_err(format!(
                    "No batch metadata registered for component '{}' (type ptr: 0x{:x})",
                    batch.component_name, batch.component_type_ptr
                ))
            },
        )?;

        // Delegate to macro-generated insert function
        (meta.insert_fn)(py, &batch, entities, world)
    }
}

/// Register the RustComponentBatch bridge so spawn_batch can detect it.
pub fn register_rust_batch_bridge() {
    Python::attach(|py| {
        let ptr = <PyRustComponentBatch as pyo3::PyTypeInfo>::type_object(py).as_type_ptr();
        global_registry::register_batch_bridge(ptr, Arc::new(RustComponentBatchBridge));
    });
}
