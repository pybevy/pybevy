#[derive(Clone, Copy, Debug)]
enum Pass {
    Forward,
    Prepass,
    Shadow,
    DepthOnly,
    Deferred,
}

impl Pass {
    fn flags(self) -> &'static [&'static str] {
        match self {
            Self::Forward => &[
                "MESH_PIPELINE",
                "VERTEX_NORMALS",
                "VERTEX_TANGENTS",
                "TONEMAP_IN_SHADER",
                "TONEMAP_METHOD_TONY_MC_MAPFACE",
                "DEBAND_DITHER",
                "SHADOW_FILTER_METHOD_GAUSSIAN",
            ],
            Self::Prepass => &[
                "PREPASS_PIPELINE",
                "VERTEX_NORMALS",
                "VERTEX_TANGENTS",
                "PREPASS_FRAGMENT",
                "DEPTH_PREPASS",
                "NORMAL_PREPASS",
                "NORMAL_PREPASS_OR_DEFERRED_PREPASS",
                "MOTION_VECTOR_PREPASS",
                "MOTION_VECTOR_PREPASS_OR_DEFERRED_PREPASS",
            ],
            Self::Shadow => &[
                "PREPASS_PIPELINE",
                "PREPASS_FRAGMENT",
                "DEPTH_PREPASS",
                "UNCLIPPED_DEPTH_ORTHO_EMULATION",
            ],
            Self::DepthOnly => &["PREPASS_PIPELINE", "DEPTH_PREPASS"],
            Self::Deferred => &[
                "PREPASS_PIPELINE",
                "VERTEX_NORMALS",
                "VERTEX_TANGENTS",
                "PREPASS_FRAGMENT",
                "DEPTH_PREPASS",
                "DEFERRED_PREPASS",
                "NORMAL_PREPASS_OR_DEFERRED_PREPASS",
                "MOTION_VECTOR_PREPASS_OR_DEFERRED_PREPASS",
            ],
        }
    }
}

const FORWARD: &[Pass] = &[Pass::Forward];
const ALL_PASSES: &[Pass] = &[Pass::Forward, Pass::Prepass, Pass::Shadow, Pass::Deferred];
const NO_FLAGS: &[&[&str]] = &[&[]];

struct Case {
    asset: &'static str,
    bindings: Option<String>,
    passes: &'static [Pass],
    flags: &'static [&'static [&'static str]],
}

fn case(asset: &'static str, bindings: Option<String>) -> Case {
    Case {
        asset,
        bindings,
        passes: FORWARD,
        flags: NO_FLAGS,
    }
}

/// Mirrors `pybevy.material._layout._generate_wgsl` plus the appended resource declarations.
fn bindings(class: &str, uniforms: &[(&str, &str)], resources: &[(u32, &str)]) -> String {
    let mut lines = vec![
        "// Auto-generated by @material - do not edit".to_owned(),
        format!("// module pybevy::gen::{class}"),
    ];
    if !uniforms.is_empty() {
        lines.push(format!("struct {class} {{"));
        lines.extend(
            uniforms
                .iter()
                .map(|(name, ty)| format!("    {name}: {ty},")),
        );
        lines.push("}".to_owned());
        lines.push(String::new());
        lines.push(format!(
            "@group(constants::MATERIAL_BIND_GROUP) @binding(100) var<uniform> material: {class};"
        ));
        lines.push(String::new());
    }
    for (binding, declaration) in resources {
        if *binding == 0 {
            lines.push((*declaration).to_owned());
        } else {
            lines.push(format!(
                "@group(constants::MATERIAL_BIND_GROUP) @binding({binding}) {declaration};"
            ));
        }
    }
    lines.join("\n")
}

fn texture(dimension: &str, sampler: Option<&str>) -> Vec<(u32, String)> {
    let mut resources = vec![(101, format!("var image: {dimension}"))];
    if let Some(sampler) = sampler {
        resources.push((102, format!("var image_sampler: {sampler}")));
    }
    resources
}

fn sampled_texture(dimension: &str, sampler: Option<&str>) -> Option<String> {
    let resources = texture(dimension, sampler);
    let resources: Vec<_> = resources.iter().map(|(b, d)| (*b, d.as_str())).collect();
    Some(bindings(
        "SampledTexture",
        &[("coord", "vec4<f32>")],
        &resources,
    ))
}

