fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn locked_version(package: &str) -> String {
    let lock = fs::read_to_string(workspace_root().join("Cargo.lock")).expect("Cargo.lock");
    let marker = format!("name = \"{package}\"\nversion = \"");
    let start = lock.find(&marker).expect("package in Cargo.lock") + marker.len();
    lock[start..start + lock[start..].find('"').unwrap()].to_owned()
}

fn files_with_extension(root: &Path, extension: &str, found: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(root).unwrap().map(Result::unwrap) {
        let path = entry.path();
        if path.is_dir() {
            files_with_extension(&path, extension, found);
        } else if path.extension().is_some_and(|value| value == extension) {
            found.push(path);
        }
    }
}

/// Bevy's embedded libraries, registered at the `embedded://<crate>/<path>` its plugins use.
fn bevy_shader_library() -> Vec<Shader> {
    let version = locked_version("bevy_pbr");
    let cargo_home = env::var_os("CARGO_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env::var_os("HOME").unwrap()).join(".cargo"));
    let suffix = format!("-{version}");
    let mut shaders = Vec::new();
    for registry in fs::read_dir(cargo_home.join("registry/src")).unwrap() {
        for package in fs::read_dir(registry.unwrap().path()).unwrap() {
            let package = package.unwrap().path();
            let name = package.file_name().unwrap().to_string_lossy().into_owned();
            let Some(crate_name) = name.strip_suffix(&suffix) else {
                continue;
            };
            if !crate_name.starts_with("bevy_") {
                continue;
            }
            let source_root = package.join("src");
            let mut files = Vec::new();
            files_with_extension(&source_root, "wesl", &mut files);
            for file in files {
                let relative = file.strip_prefix(&source_root).unwrap().to_string_lossy();
                let path = format!("embedded://{crate_name}/{relative}");
                let mut shader = Shader::from_wesl(fs::read_to_string(&file).unwrap(), path);
                if relative == "render/mesh_view_types.wesl" && crate_name == "bevy_pbr" {
                    shader.shader_defs = vec![
                        ShaderDefVal::UInt(
                            "MAX_DIRECTIONAL_LIGHTS".into(),
                            MAX_DIRECTIONAL_LIGHTS as u32,
                        ),
                        ShaderDefVal::UInt(
                            "MAX_CASCADES_PER_LIGHT".into(),
                            MAX_CASCADES_PER_LIGHT as u32,
                        ),
                        ShaderDefVal::UInt("MAX_RECT_LIGHTS".into(), MAX_RECT_LIGHTS as u32),
                    ];
                }
                shaders.push(shader);
            }
        }
    }
    assert!(
        shaders
            .iter()
            .any(|shader| shader.path == "embedded://bevy_pbr/render/forward_io.wesl"),
        "Bevy {version} shader sources not found under {}",
        cargo_home.display()
    );
    shaders
}

/// Shader assets loaded the way Bevy's `ShaderLoader` loads them.
fn asset_shaders() -> Vec<Shader> {
    let assets = workspace_root().join("assets");
    let mut files = Vec::new();
    files_with_extension(&assets.join("shaders"), "wesl", &mut files);
    files_with_extension(&assets.join("shaders"), "wgsl", &mut files);
    files
        .into_iter()
        .map(|file| {
            let path = file
                .strip_prefix(&assets)
                .unwrap()
                .to_string_lossy()
                .into_owned();
            let source = fs::read_to_string(&file).unwrap();
            if path.ends_with(".wesl") {
                Shader::from_wesl(source, path)
            } else {
                Shader::from_wgsl(source, path)
            }
        })
        .collect()
}

fn validate(
    _: &(),
    source: ShaderCacheSource,
    _: &ValidateShader,
) -> Result<String, ShaderCacheError> {
    let ShaderCacheSource::Wgsl(source) = source else {
        return Err(ShaderCacheError::CreateShaderModule("not WGSL".into()));
    };
    let module = wgsl::parse_str(&source)
        .map_err(|error| ShaderCacheError::CreateShaderModule(error.emit_to_string(&source)))?;
    Validator::new(ValidationFlags::all(), Capabilities::all())
        .validate(&module)
        .map_err(|error| ShaderCacheError::CreateShaderModule(error.emit_to_string(&source)))?;
    Ok(source)
}

struct Composer {
    cache: ShaderCache<String, ()>,
    next_id: u128,
    next_pipeline: usize,
}

impl Composer {
    fn new() -> Self {
        let mut composer = Self {
            cache: ShaderCache::new((), validate),
            next_id: 1,
            next_pipeline: 0,
        };
        for shader in bevy_shader_library() {
            composer.add(shader);
        }
        composer
    }

    fn add(&mut self, shader: Shader) -> AssetId<Shader> {
        let id = AssetId::Uuid {
            uuid: Uuid::from_u128(self.next_id),
        };
        self.next_id += 1;
        self.cache.set_shader(id, shader);
        id
    }

    fn compile(
        &mut self,
        id: AssetId<Shader>,
        pass: Pass,
        flags: &[&str],
        bindings_id: Option<u64>,
    ) -> Result<String, String> {
        let mut defs: Vec<ShaderDefVal> = GLOBAL
            .iter()
            .chain(MESH)
            .chain(pass.flags())
            .chain(flags)
            .map(|flag| ShaderDefVal::Bool((*flag).to_owned().into(), true))
            .collect();
        defs.push(ShaderDefVal::UInt(
            "AVAILABLE_STORAGE_BUFFER_BINDINGS".into(),
            8,
        ));
        defs.push(ShaderDefVal::UInt(
            "MATERIAL_BIND_GROUP".into(),
            MATERIAL_BIND_GROUP_INDEX as u32,
        ));
        defs.push(ShaderDefVal::UInt(
            "TONEMAPPING_LUT_TEXTURE_BINDING_INDEX".into(),
            TONEMAPPING_LUT_TEXTURE_BINDING_INDEX,
        ));
        defs.push(ShaderDefVal::UInt(
            "TONEMAPPING_LUT_SAMPLER_BINDING_INDEX".into(),
            TONEMAPPING_LUT_SAMPLER_BINDING_INDEX,
        ));
        if let Some(bindings_id) = bindings_id {
            defs.push(ShaderDefVal::Bool(
                binding_definition(bindings_id).into(),
                true,
            ));
        }
        self.next_pipeline += 1;
        self.cache
            .get(self.next_pipeline, id, &defs)
            .map(|module| module.as_ref().clone())
            .map_err(|error| error.to_string())
    }
}

#[test]
fn shader_assets_compose_with_bevy_wesl_library_and_generated_bindings() {
    let mut composer = Composer::new();
    let assets: HashMap<String, Shader> = asset_shaders()
        .into_iter()
        .map(|shader| (shader.path.clone(), shader))
        .collect();
    let cases = cases();
    let mut uncovered: Vec<_> = assets
        .keys()
        .filter(|path| !cases.iter().any(|case| case.asset == path.as_str()))
        .collect();
    uncovered.sort();
    assert!(
        uncovered.is_empty(),
        "shader assets without a composition case: {uncovered:?}"
    );
    assert!(
        assets.keys().all(|path| path.ends_with(".wesl")),
        "shader assets use WESL like Bevy's own assets"
    );
    let mut asset_ids = HashMap::new();
    for (path, shader) in &assets {
        asset_ids.insert(path.clone(), composer.add(shader.clone()));
    }
    let wrong_import = bindings("WrongImportMaterial", &[("color", "vec4<f32>")], &[]);
    let mut registry = BindingsRegistry::new();
    let mut generated = Assets::<Shader>::default();
    sync_generated_bindings(
        &mut registry,
        &mut generated,
        cases
            .iter()
            .filter_map(|case| case.bindings.as_deref())
            .chain([wrong_import.as_str()]),
    );
    for (_, shader) in generated.iter() {
        composer.add(shader.clone());
    }

    let mut failures = Vec::new();
    let mut compiled = 0;
    for case in &cases {
        let original = &assets[case.asset];
        let (id, bindings_id) = match case.bindings.as_deref() {
            Some(source) => {
                let import = expected_generated_material_import(source).unwrap();
                let binding_id = hash_shader_path(source);
                composer.add(generated_bindings_shader(
                    source.to_owned(),
                    &versioned_material_import(import, binding_id),
                ));
                let source = variant_source(original, import, binding_id);
                let variant = material_shader_variant(original, source, binding_id);
                (composer.add(variant), Some(binding_id))
            }
            None => (asset_ids[case.asset], None),
        };
        for pass in case.passes {
            for flags in case.flags {
                match composer.compile(id, *pass, flags, bindings_id) {
                    Ok(_) => compiled += 1,
                    Err(error) => {
                        failures.push(format!("{} {pass:?} {flags:?}:\n{error}", case.asset))
                    }
                }
            }
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n\n"));
    assert!(compiled >= cases.len());
}

#[test]
fn shared_class_names_select_their_layout_through_the_merged_module() {
    let mut composer = Composer::new();
    let first = bindings("SharedSurface", &[("color", "vec4<f32>")], &[]);
    let second = bindings(
        "SharedSurface",
        &[("padding", "vec4<f32>"), ("color", "vec4<f32>")],
        &[],
    );
    let mut registry = BindingsRegistry::new();
    let mut generated = Assets::<Shader>::default();
    sync_generated_bindings(
        &mut registry,
        &mut generated,
        [first.as_str(), second.as_str()].into_iter(),
    );
    assert_eq!(generated.len(), 1);
    for (_, shader) in generated.iter() {
        composer.add(shader.clone());
    }
    let user = composer.add(Shader::from_wesl(
        "import bevy_pbr::render::forward_io::VertexOutput;\n\
         import pybevy::gen::{SharedSurface as params};\n\n\
         @fragment\nfn fragment(in: VertexOutput) -> @location(0) vec4<f32> {\n    \
         return params::material.color;\n}\n",
        "shaders/collection_import.wesl",
    ));
    let with_padding = composer
        .compile(user, Pass::Forward, &[], Some(hash_shader_path(&second)))
        .unwrap();
    assert!(with_padding.contains("padding"), "{with_padding}");
    let without_padding = composer
        .compile(user, Pass::Forward, &[], Some(hash_shader_path(&first)))
        .unwrap();
    assert!(!without_padding.contains("padding"), "{without_padding}");
}

#[test]
fn layout_variants_keep_relative_imports_and_the_imported_module_name() {
    let mut composer = Composer::new();
    composer.add(Shader::from_wesl(
        "fn tint(color: vec4<f32>) -> vec4<f32> { return color * 0.5; }\n",
        "shaders/common/tint.wesl",
    ));
    let source = bindings("Glow", &[("color", "vec4<f32>")], &[]);
    let binding_id = hash_shader_path(&source);
    composer.add(generated_bindings_shader(
        source.clone(),
        &versioned_material_import("pybevy::gen::Glow", binding_id),
    ));
    let original = Shader::from_wesl(
        "import super::common::tint::tint;\nimport pybevy::gen::Glow;\n\n\
         @fragment\nfn fragment() -> @location(0) vec4<f32> {\n    \
         return tint(Glow::material.color);\n}\n",
        "shaders/glow.wesl",
    );
    let source = variant_source(&original, "pybevy::gen::Glow", binding_id);
    let variant = material_shader_variant(&original, source, binding_id);
    assert_eq!(variant.path, "shaders/glow.wesl");
    assert!(
        variant
            .source
            .as_str()
            .contains(&format!("import pybevy::gen_{binding_id:016x}::Glow;"))
    );
    let id = composer.add(variant);
    composer.compile(id, Pass::Forward, &[], None).unwrap();
}
